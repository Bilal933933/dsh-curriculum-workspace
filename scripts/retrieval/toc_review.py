def norm(s: str) -> str:
    """تطبيع مبسّط للمطابقة: إزالة التشكيل وتوحيد الألف/الياء/التاء."""
    s = DIACRITICS.sub("", s)
    s = (s.replace("أ", "ا").replace("إ", "ا").replace("آ", "ا").replace("ٱ", "ا")
         .replace("ى", "ي").replace("ة", "ه").replace("ؤ", "و").replace("ئ", "ي"))
    s = re.sub(r"[\(\)\[\]«»\"'،؛:,.!؟\-\u0640★✓✗xX|]", " ", s)
    return re.sub(r"\s+", " ", s).strip()


# ------------------------------------------------------------------ قراءة المسوّدة
CH_LINE = re.compile(r'^  - title: "(.*)"\s*$')
FROM_LINE = re.compile(r"^    from: (\d+)\s*$")
TO_LINE = re.compile(r"^    to: (\d+)\s*$")
TOPIC_LINE = re.compile(r'^      - \{ title: "(.*)", page: (\d+) \}\s*$')
KEY_LINE = re.compile(r"^(book_id|title|text_dir|index_dir): (.*)$")


def parse_draft(path: Path):
    meta, chapters, cur = {}, [], None
    in_chapters = False
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("chapters:"):
            in_chapters = True
            continue
        m = KEY_LINE.match(line)
        if m and not in_chapters:
            meta[m.group(1)] = m.group(2).strip().strip('"')
            continue
        if not in_chapters:
            continue
        m = CH_LINE.match(line)
        if m:
            cur = {"title": m.group(1), "from": None, "to": None, "topics": []}
            chapters.append(cur)
            continue
        m = FROM_LINE.match(line)
        if m and cur is not None:
            cur["from"] = int(m.group(1))
            continue
        m = TO_LINE.match(line)
        if m and cur is not None:
            cur["to"] = int(m.group(1))
            continue
        m = TOPIC_LINE.match(line)
        if m and cur is not None:
            cur["topics"].append({"title": m.group(1), "page": int(m.group(2))})
    return meta, chapters


def classify(title: str) -> str:
    n = norm(title)
    if not n:
        return "noise"
    # إسقاط رقم الترقيم في أول العنوان لفحص الضجيج («٧. نافذة للجميع»)
    probe = re.sub(r"^[\u0660-\u0669\d]+[.)\s]\s*", "", n)
    if NOISE_RE.search(n) or ACTIVITY_RE.search(n) or ACTIVITY_RE.search(probe):
        return "noise"
    if "اختر الاجابه" in n or "ضع علامه" in n:
        return "noise"
    if UNIT_RE.match(n):
        return "unit"
    if CHAPTER_RE.match(n):
        return "chapter"
    if LESSON_RE.match(n):
        return "lesson"
    if SECTION_RE.search(n):
        return "section"
    return "other"


# ------------------------------------------------------------------ البناء
ORDINAL_RE = re.compile(r"(الاولي|الثانيه|الثالثه|الرابعه|الخامسه|السادسه|السابعه)")
CH_ORD_RE = re.compile(r"(الاول|الثاني|الثالث|الرابع|الخامس|السادس)")


def unit_ordinal(title: str) -> str:
    """مفتاح الوحدة (الأولى/الثانية/…) لتمييز غلاف الوحدة عن سطر الفهرس."""
    n = norm(title)
    m = ORDINAL_RE.search(n)
    return m.group(1) if m else n[:30]


def chapter_ordinal(title: str) -> str:
    n = norm(title)
    m = CH_ORD_RE.search(n)
    return ("فصل-" + m.group(1)) if m else n[:30]


def page_len(text_dir: Path, page: int) -> int:
    """طول صفحة الكتاب بالحروف (0 إن لم تُوجد)."""
    p = ROOT / text_dir / f"page_{page:03d}.md"
    try:
        return len(p.read_text(encoding="utf-8").strip())
    except Exception:
        return 10_000


def build_from_headings(book_id: str, meta: dict, cap: int = 12) -> list[dict]:
    """لكتب المراجع ذات الترويسات الجارية (كل صفحة تحمل عنوان الفصل).

    المسوّدة تُولّد من كل الترويسات فتغرق في التكرار، لذلك نبني من
    `index/<book>/headings_draft.tsv` بمستويات العناوين: المستوى 1 = فصل،
    والمستويان 2 و3 = موضوعات (مع إسقاط عنوان الفصل المتكرر).
    """
    book_dir = Path(str(meta.get("text_dir", "")).strip().strip('"')).name
    tsv = ROOT / "index" / book_dir / "headings_draft.tsv"
    if not tsv.exists():
        return []
    rows = []
    for line in tsv.read_text(encoding="utf-8").splitlines():
        parts = line.split("\t")
        if len(parts) != 3 or not parts[0].isdigit():
            continue
        rows.append((int(parts[0]), int(parts[1]), parts[2].strip()))

    chapter_pages = []
    for p, lvl, title in rows:
        if lvl == 1 and CHAPTER_RE.match(norm(title)):
            key = chapter_ordinal(title)
            if chapter_pages and chapter_pages[-1]["key"] == key:
                continue
            chapter_pages.append({"page": p, "title": title, "key": key})
    if not chapter_pages:
        return []

    last_page = max((r[0] for r in rows), default=1)
    out = []
    if chapter_pages[0]["page"] > 3:
        out.append({"title": "مقدمة الكتاب", "from": 1, "to": chapter_pages[0]["page"] - 1,
                    "topics": [{"title": "مقدمة الكتاب", "page": 2}]})

    for i, ch in enumerate(chapter_pages):
        start = ch["page"]
        end = (chapter_pages[i + 1]["page"] - 1) if i + 1 < len(chapter_pages) else last_page
        subtitle = next((t for p, lvl, t in rows
                         if p == start and lvl == 2 and not CHAPTER_RE.match(norm(t))), "")
        title = f"{ch['title']}: {subtitle}" if subtitle else ch["title"]
        seen, topics = set(), []
        for p, lvl, t in rows:
            if not (start <= p <= end) or lvl < 2:
                continue
            if CHAPTER_RE.match(norm(t)) or UNIT_RE.match(norm(t)):
                continue
            if not (4 <= len(t) <= 60):
                continue
            key = norm(t)
            if key in seen:
                continue
            seen.add(key)
            topics.append({"title": t, "page": p, "kind": "section"})
        out.append({"title": title, "from": start, "to": end, "topics": topics[:cap]})
    return out


