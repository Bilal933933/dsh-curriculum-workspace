def build_school(meta: dict, chapters: list[dict], book_id: str = "", cap: int = 16) -> list[dict]:
    """لبناء الكتب المدرسية: فصول من الوحدات، وموضوعات من الدروس/المحاور.

    صفحات الفهرس تكرّر عناوين الوحدات، فتُنتج «وحدات» وهمية. الفارق أن غلاف
    الوحدة صفحة شبه فارغة (عنوان فقط) بينما صفحة الفهرس مكتظة. لذلك نعتمد على
    طول صفحة المخرجات لا على موضع الصفحة.
    """
    text_dir = Path(str(meta.get("text_dir", "")).strip().strip('"'))
    topics = sorted((t for ch in chapters for t in ch["topics"]), key=lambda t: t["page"])

    picked: "OrderedDict[str, dict]" = OrderedDict()
    ovr = BOOK_UNIT_OVERRIDES.get(book_id)
    if ovr:
        # الحدود اليدوية مرجعٌ حصري (كتب المنهج الجديد — أغلف وحداتها غنية المحتوى)
        for p, ti in ovr:
            picked[unit_ordinal(ti)] = {"title": ti, "page": p}
    else:
        dividers = [t for t in topics if classify(t["title"]) == "unit"
                    and page_len(text_dir, t["page"]) < 700]
        pool = dividers or [t for t in topics if classify(t["title"]) == "unit"]
        for t in sorted(pool, key=lambda x: x["page"]):
            key = unit_ordinal(t["title"])
            if key not in picked:          # أول غلاف لكل وحدة
                picked[key] = t

    # أغلفة معروفة يدويًّا (صفحة كانت ناقصة وقت توليد المسوّدة)
    for page, title in UNIT_OVERRIDES.get(book_id, []):
        picked.setdefault(unit_ordinal(title), {"title": title, "page": page})

    units = sorted(picked.values(), key=lambda t: t["page"])

    last_page = max((t["page"] for t in topics), default=1)
    # آخر صفحة في الكتاب من ملفات المخرجات نفسها (لا من آخر عنوان) حتى لا
    # تُقتطع الملاحق والجداول التي لا تحمل عنوانًا.
    page_files = sorted((ROOT / text_dir).glob("page_*.md"))
    if page_files:
        try:
            last_page = max(last_page, int(page_files[-1].stem.split("_")[1]))
        except (IndexError, ValueError):
            pass
    out = []

    def clean(items, limit):
        """إسقاط الضجيج وتكرار العناوين، مع أولوية الدروس والمحاور."""
        seen_titles, bucket = set(), {"chapter": [], "lesson": [], "section": [], "other": []}
        # عناوين مجردة لا تحمل موضوعًا: «الدرس الأول» / «الوحدة الثانية» / «المفهوم الأول»
        bare = re.compile(r"^(الدرس|الوحده|الوحدة|المفهوم|المحور|الفصل)\s+(الاول|الاولي|الثاني|الثانيه|الثالث|الثالثه|الرابع|الرابعه|الخامس|الخامسه|السادس|السادسه|السابع|السابعه|الثامن|التاسع|العاشر|[\u0660-\u0669\d]+)(\s+\d+)?$")
        # كلمة ترتيب وحدها («الثانية») شذرة من غلاف وحدة لا موضوعًا
        lone_ordinal = re.compile(r"^(الاولي|الثانيه|الثالثه|الرابعه|الخامسه|السادسه|السابعه|الثامنه|التاسعه|العاشره)$")
        # شذرات قوائم مرقّمة داخل الصفحة: «١ ملحقات الحاسب الآلي:»
        fragment = re.compile(r"^[\u0660-\u0669\d]+\s+\S")
        # عناوين الدروس المرقّمة «١-١ …» ليست شذرة قائمة — تبقى موضوعات
        lesson_number = re.compile(r"^[\u0660-\u0669\d]+\s+[\u0660-\u0669\d]+\s+\S")
        kept: list[dict] = []
        for t in items:
            kind = classify(t["title"])
            if kind in ("noise", "unit"):
                continue
            raw = norm(t["title"])
            # تجاهل أرقام الترقيم في مفتاح التكرار: «١-٢ الجمع…» و«٢-١ الجمع…» عنوان واحد
            key = re.sub(r"[\u0660-\u0669\d]+", " ", raw).strip()
            key = re.sub(r"\s+", " ", key)
            if key in seen_titles:
                continue
            if bare.match(raw) or lone_ordinal.match(raw):
                continue
            if fragment.match(raw) and kind in ("other", "section") and not lesson_number.match(raw):
                continue
            seen_titles.add(key)
            if kind == "other" and len(t["title"]) > 48:
                continue
            kept.append({"title": t["title"], "page": t["page"], "kind": kind})

        # تكرار جزئي: عنوان قصير يُعاد داخل عنوان أطول في الصفحة نفسها أو التالية
        final: list[dict] = []
        for a in kept:
            na = norm(a["title"])
            redundant = any(
                b is not a and abs(b["page"] - a["page"]) <= 1
                and len(norm(b["title"])) > len(na)
                and (norm(b["title"]).startswith(na) or na in norm(b["title"]))
                for b in kept
            )
            if not redundant:
                final.append(a)

        for t in final:
            bucket[t["kind"]].append(t)
        chosen = bucket["chapter"] + bucket["lesson"] + bucket["section"] + bucket["other"]
        chosen = sorted(chosen, key=lambda x: x["page"])
        if len(chosen) > limit:
            # عند تجاوز الحد: تُقدَّم الدروس على الشروح الفرعية كي لا تُقتطع دروس
            pri = [t for t in chosen if t["kind"] in ("chapter", "lesson")]
            rest = [t for t in chosen if t["kind"] not in ("chapter", "lesson")]
            keep = pri[:limit]
            keep += rest[: max(0, limit - len(keep))]
            chosen = sorted(keep, key=lambda x: x["page"])
        return chosen

    intro_to = (units[0]["page"] - 1) if units else last_page
    if intro_to >= 3:
        out.append({"title": "مقدمة الكتاب والفهرس", "from": 1, "to": intro_to,
                    "topics": [{"title": "مقدمة الكتاب", "page": 2},
                               {"title": "الفهرس", "page": min(4, intro_to)}]})

    for i, u in enumerate(units):
        start = u["page"]
        end = (units[i + 1]["page"] - 1) if i + 1 < len(units) else last_page
        if end < start:
            continue
        inner = [t for t in topics if start <= t["page"] <= end]
        chosen = clean(inner, cap)
        # موضوع يكرر عنوان الوحدة/الفصل نفسه ليس موضوعًا مستقلًّا
        nt = norm(u["title"])
        chosen = [t for t in chosen
                  if not (len(norm(t["title"])) > 8 and norm(t["title"]) in nt)]
        head = nt.split(" ")[0]
        if head in ("الفصل", "الوحده"):
            chosen = [t for t in chosen if not norm(t["title"]).startswith(head)]
        title = u["title"]
        if len(norm(title)) <= 14:
            # غلاف بلا موضوع (مثل «الوحدة الثانية») ⇒ نضيف عنوان الوحدة/أول درس
            theme = next((t["title"] for t in chosen
                          if t["kind"] == "other" and len(t["title"]) <= 34
                          and t["page"] <= start + 1), "")
            if theme and norm(theme) in norm(title):
                theme = ""            # لا نضيف ما يكرر عنوان الوحدة («الجبر: الجبر»)
            title = f"{title}: {theme}" if theme else title
        out.append({"title": TITLE_OVERRIDES.get((book_id, start), title),
                    "from": start, "to": end, "topics": chosen})

    # دمج دروس جدول المحتويات المعتمدة في فصلها (نمط المنهج الجديد)
    extra = BOOK_LESSON_TOPICS.get(book_id, [])
    for ch in out:
        keep = [{"title": t, "page": p} for p, t in extra
                if ch["from"] <= p <= ch["to"]]
        if keep:
            have_pages = {x["page"] for x in keep}
            kept_titles = {norm(x["title"]) for x in keep}
            rest = [x for x in ch["topics"]
                    if x["page"] not in have_pages and norm(x["title"]) not in kept_titles]
            ch["topics"] = sorted(keep + rest, key=lambda x: x["page"])

    return out


def build_chaptered(chapters: list[dict]) -> list[dict]:
    """لكتب المراجع ذوات الفصول: ندمج الفصول المكررة ونحذف التكرار والضجيج."""
    merged: "OrderedDict[str, dict]" = OrderedDict()
    for ch in chapters:
        key = chapter_ordinal(ch["title"])
        slot = merged.get(key)
        if slot is None:
            slot = {"title": ch["title"], "from": ch["from"], "to": ch["to"], "topics": []}
            merged[key] = slot
        else:
            if ch["from"]:
                slot["from"] = min(slot["from"] or ch["from"], ch["from"])
            if ch["to"]:
                slot["to"] = max(slot["to"] or ch["to"], ch["to"])

    out = []
    for key, slot in merged.items():
        kept, seen = [], set()
        for ch in chapters:
            if chapter_ordinal(ch["title"]) != key:
                continue
            for t in ch["topics"]:
                if classify(t["title"]) == "noise":
                    continue
                key = (norm(t["title"]), t["page"])
                if key in seen:
                    continue
                # العنوان المطابق لعنوان الفصل ليس موضوعًا مستقلًّا
                if norm(t["title"]) == norm(ch["title"]):
                    continue
                seen.add(key)
                kept.append({"title": t["title"], "page": t["page"], "kind": classify(t["title"])})
        if not kept:
            continue
        out.append({"title": slot["title"], "from": slot["from"], "to": slot["to"], "topics": kept})
    return out


def keywords_for(chapter: dict, limit: int = 10) -> list[str]:
    """كلمات مفتاحية مُطبَّعة من عناوين الفصل نفسه (بلا تكرار وبلا وظيفيات)."""
    words = OrderedDict()
    for t in chapter["topics"]:
        for w in norm(t["title"]).split():
            if len(w) < 3 or w in STOPWORDS:
                continue
            words.setdefault(w, 0)
            words[w] += 1
    ranked = sorted(words.items(), key=lambda kv: (-kv[1], kv[0]))
    return [w for w, _ in ranked][:limit]


# ------------------------------------------------------------------ الكتابة
def q(s: str) -> str:
    return '"' + (s or "").replace('"', "'").replace("\n", " ") + '"'


def keywords_all(chapters: list[dict]) -> list[list[str]]:
    """كلمات مفتاحية لكل فصل مع إسقاط الشائع في أغلب الفصول (لا يميّز شيئًا)."""
    per_chapter = [keywords_for(ch, limit=40) for ch in chapters]
    df: dict[str, int] = {}
    for kws in per_chapter:
        for w in set(kws):
            df[w] = df.get(w, 0) + 1
    n = max(len(chapters), 1)
    out = []
    for kws in per_chapter:
        kept = [w for w in kws if df.get(w, 0) <= max(2, n // 2)]
        out.append(kept[:10])
    return out


def emit(meta: dict, chapters: list[dict], book_id: str) -> str:
    lines = [
        "# ============================================================================",
        f"# خريطة موضوعات: {meta.get('title', '')}",
        "# ----------------------------------------------------------------------------",
        "# حُدِّدت من عناوين الكتاب ثم نظّفها المشغّل آليًّا (scripts/toc_review.py):",
        "#   - أُسقطت مدخلات التمارين والإجابات والفهارس والتكرارات.",
        "#   - جُمِعت الوحدات في فصول، والمحاور (استماع/قراءة/قواعد…) في موضوعات.",
        "#   - أُضيفت keywords مُطبَّعة (بلا تشكيل) لكل فصل لتضييق البحث في index/.",
        "# - أكواد الصفحات أرقام ملفات page_XXX.md لا أرقام المطبوع.",
        "# ============================================================================",
        "",
        f"book_id: {book_id}",
        f"title: {q(meta.get('title', ''))}",
        f"text_dir: {q(meta.get('text_dir', ''))}",
        f"index_dir: {q(meta.get('index_dir', ''))}",
        "reviewed: true",
        f'derived_from: "meta/books/{book_id}/toc.draft.yaml"',
        "",
        "chapters:",
    ]
    all_kws = keywords_all(chapters)
    for ch, kws in zip(chapters, all_kws):
        lines.append(f"  - title: {q(ch['title'])}")
        lines.append(f"    from: {ch['from']}")
        lines.append(f"    to: {ch['to']}")
        if kws:
            lines.append("    keywords: [" + ", ".join(kws) + "]")
        if ch["topics"]:
            lines.append("    topics:")
            for t in ch["topics"]:
                lines.append(f"      - {{ title: {q(t['title'])}, page: {t['page']} }}")
        else:
            lines.append("    topics: []")
        lines.append("")
    return "\n".join(lines)


def validate() -> int:
    """فحص سلامة كل toc.yaml: نطاقات معقولة، وموضوعات داخل نطاق فصلها."""
    import pymupdf  # فقط لعدد صفحات المصدر

    problems = 0
    for dest in sorted(META_BOOKS.glob("*/toc.yaml")):
        book_id = dest.parent.name
        txt = dest.read_text(encoding="utf-8")
        text_dir = re.search(r'^text_dir: "(.*)"$', txt, re.M)
        chapters, cur = [], None
        for line in txt.splitlines():
            m = re.match(r'^  - title: "(.*)"$', line)
            if m:
                cur = {"title": m.group(1), "from": None, "to": None, "topics": []}
                chapters.append(cur)
                continue
            m = re.match(r"^    from: (\d+)$", line)
            if m and cur:
                cur["from"] = int(m.group(1))
                continue
            m = re.match(r"^    to: (\d+)$", line)
            if m and cur:
                cur["to"] = int(m.group(1))
                continue
            m = re.match(r'^      - \{ title: "(.*)", page: (\d+) \}$', line)
            if m and cur:
                cur["topics"].append((m.group(1), int(m.group(2))))

        total = 0
        if text_dir:
            pdf = ROOT / "curriculum_raw" / (Path(text_dir.group(1)).name + ".pdf")
            if pdf.exists():
                total = pymupdf.open(pdf).page_count

        errs = []
        prev_to = 0
        for ch in chapters:
            if ch["from"] is None or ch["to"] is None:
                errs.append(f"نطاق ناقص: {ch['title']}")
                continue
            if ch["from"] > ch["to"]:
                errs.append(f"نطاق معكوس: {ch['title']}")
            if total and ch["to"] > total:
                errs.append(f"تجاوز صفحات المصدر: {ch['title']}")
            if ch["from"] < prev_to:
                errs.append(f"تداخل مع الفصل السابق: {ch['title']}")
            prev_to = ch["to"]
            for title, page in ch["topics"]:
                if not (ch["from"] <= page <= ch["to"]):
                    errs.append(f"موضوع خارج النطاق «{title}» ص{page} ∉ [{ch['from']},{ch['to']}]")
        if errs:
            problems += len(errs)
            print(f"[✗] {book_id}")
            for e in errs[:6]:
                print(f"     - {e}")
        else:
            print(f"[✓] {book_id}: {len(chapters)} فصلًا، نطاقات سليمة"
                  + (f" من {total} صفحة" if total else ""))
    print(f"\nالنتيجة: {'سليم' if problems == 0 else str(problems) + ' مشكلة'}")
    return 0 if problems == 0 else 1


def process(book_id: str, report: bool = False) -> None:
    draft = META_BOOKS / book_id / "toc.draft.yaml"
    if not draft.exists():
        print(f"[!] لا مسوّدة: {draft}")
        return
    meta, chapters = parse_draft(draft)
    n_topics = sum(len(c["topics"]) for c in chapters)
    units = sum(1 for c in chapters for t in c["topics"] if classify(t["title"]) == "unit")

    if units >= 2 or book_id in BOOK_UNIT_OVERRIDES:
        built = build_school(meta, chapters, book_id=book_id)
        kind = "مدرسي"
    else:
        # مرجع ذو ترويسات جارية: البناء من مستويات العناوين أدق من المسوّدة
        built = build_from_headings(book_id, meta) or build_chaptered(chapters)
        kind = "مرجعي"

    kept = sum(len(c["topics"]) for c in built)
    print(f"\n=== {book_id} ({kind}) — مسوّدة {n_topics} موضوعًا ⇒ {len(built)} فصلًا / {kept} موضوعًا")
    for ch in built:
        preview = " | ".join(t["title"][:34] for t in ch["topics"][:5])
        print(f"   • {ch['title'][:60]}  [{ch['from']}–{ch['to']}]  ({len(ch['topics'])})  {preview[:110]}")

    if report:
        return
    dest = META_BOOKS / book_id / "toc.yaml"
    dest.write_text(emit(meta, built, book_id), encoding="utf-8")
    print(f"   [✓] كُتب {dest.relative_to(ROOT)}")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--book", help="معرّف كتاب واحد")
    ap.add_argument("--all", action="store_true")
    ap.add_argument("--report", action="store_true", help="معاينة بلا كتابة")
    ap.add_argument("--validate", action="store_true", help="فحص سلامة toc.yaml فقط")
    args = ap.parse_args()

    if args.validate:
        return validate()

    ids = ([args.book] if args.book else
           [p.parent.name for p in sorted(META_BOOKS.glob("*/toc.draft.yaml"))])
    if not ids:
        print("لا مسوّدات.")
        return 1
    for b in ids:
        process(b, report=args.report)
    return 0


if __name__ == "__main__":
    sys.exit(main())
