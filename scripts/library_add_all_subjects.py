def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()

def pages(path: Path) -> int:
    """عدد الصفحات — سالب يعني «غير مقيس» (تعطُّل pymupdf) ولا يعطّل النقل."""
    if fitz is None:
        return -1
    try:
        with fitz.open(path) as doc:
            return doc.page_count
    except Exception:
        return 0

def q(value) -> str:
    """تنسيق قيمة YAML بين نص آمن."""
    if value is None:
        return "null"
    if isinstance(value, bool):
        return str(value).lower()
    if isinstance(value, int):
        return str(value)
    text = str(value).replace("\\", "\\\\").replace('"', '\\"')
    return f'"{text}"'

